import os

from qgis.PyQt import uic
from qgis.PyQt import QtWidgets

# This loads your .ui file so that PyQt can populate your plugin with the elements from Qt Designer
FORM_CLASS, _ = uic.loadUiType(os.path.join(
    os.path.dirname(__file__), 'locatefabric_dialog_base.ui'))


class LocateFabricDialog(QtWidgets.QDialog, FORM_CLASS):
    def __init__(self, parent=None):
        """Constructor."""
        super(LocateFabricDialog, self).__init__(parent)
        # Set up the user interface from Designer through FORM_CLASS.
        # After self.setupUi() you can access any designer object by doing
        # self.<objectname>, and you can use autoconnect slots - see
        # http://qt-project.org/doc/qt-4.8/designer-using-a-ui-file.html
        # #widgets-and-dialogs-with-auto-connect
        self.setupUi(self)
        self._initConnections()
        self.checkBox_CSV.setChecked(False)
        self.infoBox_input.setVisible(True)
        self.infoBox_input.setEnabled(True)
        self.mQgsFileWidget.setVisible(False)
        self.mQgsFileWidget.setEnabled(False)
    
    def _initConnections(self):
        self.checkBox_CSV.toggled.connect(self._onCSVChecked)
        self.AddrButton.toggled.connect(self._onBtnChecked)
        self.CoorButton.toggled.connect(self._onBtnChecked)
    
    def _onCSVChecked(self):
        """
        Handle the change in search type.
        """
        if self.checkBox_CSV.isChecked():
            # Make infoBox_input invisible and mQgsFileWidget visible
            self.infoBox_input.setVisible(False)
            self.infoBox_input.setEnabled(False)
            self.mQgsFileWidget.setVisible(True)
            self.mQgsFileWidget.setEnabled(True)
            if self.AddrButton.isChecked():
                self.infoBox_tips.setText(
                    "Please prepare a CSV file with required columns: [Sourcekey, Address]")
            if self.CoorButton.isChecked():
                self.infoBox_tips.setText(
                    "Please prepare a CSV file with required columns: [Sourcekey, Latitude, Longitude]")

        else:
            self.infoBox_input.setVisible(True)
            self.infoBox_input.setEnabled(True)
            self.mQgsFileWidget.setVisible(False)
            self.mQgsFileWidget.setEnabled(False)
            if self.AddrButton.isChecked():
                self.infoBox_tips.setText("Please enter a single line address in the input box.(e.g., 123 Main St, City, State, Zip Code)")
            if self.CoorButton.isChecked():
                self.infoBox_tips.setText("Please enter latitude and longitude in the input box, separated by a comma (e.g., 36.660,-80.924).")
    
    
    def _onBtnChecked(self):
        """
        Handle the change in search type.
        """
        if self.checkBox_CSV.isChecked():
            if self.AddrButton.isChecked():
                self.infoBox_tips.setText(
                    "Please prepare a CSV file with required columns: [Sourcekey, Address]")
            if self.CoorButton.isChecked():
                self.infoBox_tips.setText(
                    "Please prepare a CSV file with required columns: [Sourcekey, Latitude, Longitude]")

        else:
            if self.AddrButton.isChecked():
                self.infoBox_tips.setText("Please enter a single line address in the input box.(e.g., 123 Main St, City, State, Zip Code)")
            if self.CoorButton.isChecked():
                self.infoBox_tips.setText("Please enter latitude and longitude in the input box, separated by a comma (e.g., 36.660,-80.924).")
  
